// Turns an AI action config (configs/{name}.json) into a GitHub Actions
// workflow that runs pi with its prompt on its schedule and opens a pull
// request with what it changed. scripts/generate-workflows.js writes them.
//
// A config: { "cron": "daily", "prompt": "…", "model": "claude-opus-5-5",
// "provider": "anthropic" }. `cron` is "hourly", "daily", "weekly" or a
// five-field cron expression (UTC).

const GENERATED_MARKER = "# Generated by packages/ai-action-configs";
const NAME = /^[a-z0-9][a-z0-9-]{0,48}$/;
const CRON = /^(\S+\s+){4}\S+$/;

// The secret each provider's API key comes from, as pi reads it
// (docs/providers.md); providers not listed use {PROVIDER}_API_KEY.
const PROVIDER_KEYS = {
  anthropic: "ANTHROPIC_API_KEY",
  openai: "OPENAI_API_KEY",
  google: "GEMINI_API_KEY",
  mistral: "MISTRAL_API_KEY",
  zai: "ZAI_API_KEY",
  openrouter: "OPENROUTER_API_KEY",
};

const apiKeyName = (provider) =>
  PROVIDER_KEYS[provider] ?? `${provider.toUpperCase().replace(/[^A-Z0-9]/g, "_")}_API_KEY`;

// A stable minute per config, so they don't all start at once.
const minuteOf = (name) => [...name].reduce((sum, char) => sum + char.charCodeAt(0), 0) % 60;

const cronOf = (name, schedule) => {
  const minute = minuteOf(name);
  if (schedule === "hourly") {
    return `${minute} * * * *`;
  }
  if (schedule === "daily") {
    return `${minute} 6 * * *`;
  }
  if (schedule === "weekly") {
    return `${minute} 6 * * 1`;
  }
  return schedule;
};

// The config's problems, as messages; none if it's valid.
const configErrors = (name, config) => {
  const errors = [];
  if (!NAME.test(name)) {
    errors.push(`${name}: the file name must be lowercase letters, digits and dashes`);
  }
  const { cron, prompt, model, provider } = config ?? {};
  if (!["hourly", "daily", "weekly"].includes(cron) && !CRON.test(cron ?? "")) {
    errors.push(`${name}: cron must be hourly, daily, weekly or a cron expression`);
  }
  for (const [field, value] of Object.entries({ prompt, model, provider })) {
    if (typeof value !== "string" || !value.trim()) {
      errors.push(`${name}: ${field} is required`);
    }
  }
  return errors;
};

// Added to every prompt: pi's final message becomes the pull request's
// description, so a reviewer sees what changed without reading the job log.
const REPORT_INSTRUCTION =
  "Your final message becomes the description of the pull request with your changes, " +
  "so write it in Markdown for its reviewer: what you changed and why (for an upgrade, " +
  "each package or tool with the version it went from and to), and what you checked but " +
  "left alone, and why. If you changed nothing, say why.";

// JSON strings are YAML double-quoted strings, escapes and all.
const yamlString = (value) => JSON.stringify(value);

const workflowOf = (name, { cron, prompt, model, provider }) => {
  const key = apiKeyName(provider);
  return `${GENERATED_MARKER} from configs/${name}.json.
# Edit the config, not this file: the AI actions workflow regenerates it.
name: ${yamlString(`AI: ${name}`)}

on:
  schedule:
    - cron: ${yamlString(cronOf(name, cron))}
  workflow_dispatch:

permissions:
  contents: write
  pull-requests: write

concurrency:
  group: ai-${name}
  cancel-in-progress: false

jobs:
  run:
    name: Run the prompt
    runs-on: ubuntu-latest
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@v7

      - uses: oven-sh/setup-bun@v2
        with:
          bun-version-file: package.json

      - uses: actions/setup-node@v7
        with:
          node-version-file: package.json

      - name: Install dependencies
        run: bun install --frozen-lockfile

      - name: Install pi
        run: npm install -g --ignore-scripts @earendil-works/pi-coding-agent

      # --no-approve: only the prompt's model, without the repository's own pi
      # setup (.pi), and no session saved on the runner. pi's final message,
      # its report of what it did, is kept for the pull request's description
      # (bash: pipefail, so a failing pi still fails the step).
      - name: Run the prompt with pi
        shell: bash
        env:
          ${key}: \${{ secrets.${key} }}
          PROMPT: ${yamlString(prompt)}
          REPORT_INSTRUCTION: ${yamlString(REPORT_INSTRUCTION)}
        run: >-
          pi --print --no-session --no-approve
          --provider ${yamlString(provider)} --model ${yamlString(model)}
          "$PROMPT"$'\\n\\n'"$REPORT_INSTRUCTION"
          | tee "$RUNNER_TEMP/pi-report.md"

      - name: Write the pull request's description
        shell: bash
        env:
          HEADER: ${yamlString(
            `Made by pi (${provider}/${model}) running packages/ai-action-configs/configs/${name}.json:`
          )}
          PROMPT: ${yamlString(prompt)}
        run: |
          {
            printf '%s\\n\\n' "$HEADER"
            printf '%s\\n' "$PROMPT" | sed 's/^/> /'
            printf '\\n---\\n\\n'
            cat "$RUNNER_TEMP/pi-report.md"
          } > "$RUNNER_TEMP/pull-request-body.md"

      - name: Open a pull request with the changes
        uses: peter-evans/create-pull-request@v8
        with:
          token: \${{ secrets.AI_ACTIONS_TOKEN || github.token }}
          branch: ai/${name}
          delete-branch: true
          title: ${yamlString(`AI: ${name}`)}
          commit-message: ${yamlString(`chore: ${name} (AI action)`)}
          body-path: \${{ runner.temp }}/pull-request-body.md
`;
};

export { GENERATED_MARKER, REPORT_INSTRUCTION, apiKeyName, configErrors, cronOf, workflowOf };
